/*
 * wireshark-web — engine worker.
 *
 * Owns the Wiregasm module (Wireshark compiled to WASM): loads and inflates
 * the gzipped engine assets, initializes the dissectors, and answers RPCs
 * from the page. Everything here is plain ES module syntax — no bundler, no
 * external resources.
 *
 * The engine assets are fetched as .gz (~21 MB) instead of raw (~74 MB) and
 * inflated in the worker with pako; the inflated bytes go straight into the
 * module via wasmBinary / getPreloadedPackage, so the wiregasm loader never
 * issues its own network requests.
 */

'use strict';

/* pako (inflate only), vendored under vendor/. Sets self.pako. */
importScripts('../vendor/pako-inflate.min.js');
/* The emscripten module, generated by CI into wasm/engine/. Sets no global:
 * with MODULARIZE=1 + EXPORT_NAME=loadWiregasm it defines self.loadWiregasm. */
importScripts('../wasm/engine/wiregasm.js');

if (typeof self.loadWiregasm !== 'function') {
  throw new Error('wasm/engine/wiregasm.js did not define loadWiregasm');
}

/* --------------------------------------------------------------- helpers */

/* Fetch a binary asset with progress events reported to the page. */
async function fetchAsset(url, kind, onProgress) {
  const response = await fetch(url, { cache: 'force-cache' });
  if (!response.ok) throw new Error(`${response.status} ${response.statusText} for ${url}`);
  const total = Number(response.headers.get('Content-Length') || 0);
  if (!response.body || !total) return new Uint8Array(await response.arrayBuffer());
  const reader = response.body.getReader();
  const chunks = [];
  let loaded = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    chunks.push(value);
    loaded += value.length;
    if (onProgress) onProgress(kind, loaded, total);
  }
  const out = new Uint8Array(loaded);
  let off = 0;
  for (const c of chunks) { out.set(c, off); off += c.length; }
  return out;
}

function inflate(gz) {
  const out = self.pako.inflate(gz);
  if (!(out instanceof Uint8Array)) throw new Error('pako.inflate returned no bytes');
  return out;
}

/* Convert an embind Vector<T> to a plain array and free the vector. */
function vec2array(v) {
  if (v == null) return [];
  const out = [];
  const n = v.size();
  for (let i = 0; i < n; i++) out.push(v.get(i));
  if (typeof v.delete === 'function') v.delete();
  return out;
}

/* ProtoTree / Frame objects (and their nested vectors) to plain objects. */
function plainTree(t) {
  return {
    label: t.label,
    filter: t.filter,
    severity: t.severity,
    type: t.type,
    url: t.url,
    fnum: t.fnum,
    start: t.start,
    length: t.length,
    data_source_idx: t.data_source_idx,
    tree: vec2array(t.tree).map(plainTree)
  };
}

function plainFrame(f) {
  return {
    number: f.number,
    comments: vec2array(f.comments),
    data_sources: vec2array(f.data_sources).map(function (ds) { return { name: ds.name, data: ds.data }; }),
    tree: vec2array(f.tree).map(plainTree),
    follow: vec2array(f.follow).map(vec2array)
  };
}

function plainFrameMeta(m) {
  return {
    number: m.number,
    comments: m.comments,
    ignored: m.ignored,
    marked: m.marked,
    bg: m.bg,
    fg: m.fg,
    columns: vec2array(m.columns)
  };
}

function plainFollow(f) {
  return {
    shost: f.shost, sport: f.sport, sbytes: f.sbytes,
    chost: f.chost, cport: f.cport, cbytes: f.cbytes,
    payloads: vec2array(f.payloads).map(function (p) {
      return { number: p.number, server: p.server === 1, data: p.data };
    })
  };
}

/* Tap results: either a conversation/endpoint tap or an export-objects tap. */
function plainTap(tap) {
  const base = { tap: tap.tap, type: tap.type, proto: tap.proto };
  let res = base;
  if ('convs' in tap && tap.convs != null) {
    res = Object.assign(base, {
      geoip: tap.geoip,
      convs: vec2array(tap.convs),
      hosts: vec2array(tap.hosts)
    });
  } else if ('objects' in tap && tap.objects != null) {
    res = Object.assign(base, { objects: vec2array(tap.objects) });
  }
  if (typeof tap.delete === 'function') tap.delete();
  return res;
}

/* --------------------------------------------------------------- engine */

let lib = null;             /* the emscripten module once loaded */
let session = null;         /* the DissectSession for the current capture */
let fileName = null;
let lastSummary = null;
let loadSeq = 0;            /* monotonic token: stale replies are dropped */

async function initEngine(onProgress) {
  const base = new URL('../wasm/engine/', self.location);

  const [wasmGz, dataGz] = await Promise.all([
    fetchAsset(new URL('wiregasm.wasm.gz', base), 'wasm', onProgress),
    fetchAsset(new URL('wiregasm.data.gz', base), 'data', onProgress)
  ]);
  onProgress('inflate', 0, 1);
  const wasm = inflate(wasmGz);
  const data = inflate(dataGz);
  onProgress('inflate', 1, 1);

  lib = await self.loadWiregasm({
    wasmBinary: wasm.buffer,
    getPreloadedPackage: function () { return data.buffer; },
    handleStatus: function (type, message) {
      send({ type: 'engine-status', code: type, status: message });
    },
    print: function (text) {
      if (text && !/^\d+ /.test(text)) send({ type: 'engine-log', level: 'log', text: String(text) });
    },
    printErr: function (text) {
      /* Epan logs dissectors' INFO chatter to stderr; only surface warnings. */
      if (text && !/\[Epan INFO\]|\[DFilter INFO\]/.test(String(text))) {
        send({ type: 'engine-log', level: 'warn', text: String(text) });
      }
    }
  });

  if (!lib.init()) throw new Error('engine init failed');

  send({
    type: 'engine-ready',
    version: lib.wiresharkVersion(),
    columns: vec2array(lib.getColumns())
  });
}

/* ------------------------------------------------------------- capture */

function destroySession() {
  if (session != null) {
    try { session.delete(); } catch (e) { /* already deleted */ }
    session = null;
  }
}

/* Read the uploaded File into the emscripten FS and dissect it. */
async function loadCapture(file) {
  const seq = ++loadSeq;
  const bytes = new Uint8Array(await file.arrayBuffer());
  if (seq !== loadSeq) return; /* superseded by a newer load */

  const uploadDir = lib.getUploadDirectory();
  /* lib.FS.writeFile only accepts paths without traversal; the upload dir
 * exists (created by the loader's onRuntimeInitialized). */
  const name = file.name || 'capture';
  lib.FS.writeFile(uploadDir + '/' + name.replace(/[\/\\]/g, '_'), bytes);
  destroySession();

  const t0 = performance.now();
  session = new lib.DissectSession(uploadDir + '/' + name.replace(/[\/\\]/g, '_'));
  const response = session.load();
  const elapsed = Math.round(performance.now() - t0);

  if (seq !== loadSeq) return;

  if (response.code !== 0) {
    destroySession();
    send({ type: 'load-error', seq: seq, error: response.error || 'the capture could not be opened' });
    return;
  }

  fileName = name;
  lastSummary = {
    filename: response.summary.filename,
    file_type: response.summary.file_type,
    file_length: response.summary.file_length,
    file_encap_type: response.summary.file_encap_type,
    packet_count: response.summary.packet_count,
    start_time: response.summary.start_time,
    stop_time: response.summary.stop_time,
    elapsed_time: response.summary.elapsed_time
  };
  send({ type: 'loaded', seq: seq, name: name, summary: lastSummary, ms: elapsed });
}

/* --------------------------------------------------------------- RPCs */

const handlers = {
  'engine-init': async function (msg) {
    try {
      await initEngine(function (kind, loaded, total) {
        send({ type: 'engine-progress', kind: kind, loaded: loaded, total: total });
      });
    } catch (err) {
      send({ type: 'engine-error', error: String(err && err.message || err) });
    }
  },

  'load': async function (msg) {
    if (!lib) return send({ type: 'load-error', seq: loadSeq, error: 'engine not ready' });
    try {
      await loadCapture(msg.file);
    } catch (err) {
      send({ type: 'load-error', seq: loadSeq, error: String(err && err.message || err) });
    }
  },

  'frames': function (msg) {
    if (!session) return send({ type: 'frames', seq: msg.seq, error: 'no capture loaded', frames: [], matched: 0 });
    try {
      const res = session.getFrames(msg.filter || '', msg.skip | 0, msg.limit | 0);
      send({
        type: 'frames', seq: msg.seq,
        frames: vec2array(res.frames).map(plainFrameMeta),
        matched: res.matched
      });
    } catch (err) {
      send({ type: 'frames', seq: msg.seq, error: String(err && err.message || err), frames: [], matched: 0 });
    }
  },

  'frame': function (msg) {
    if (!session) return send({ type: 'frame', seq: msg.seq, error: 'no capture loaded' });
    try {
      const res = session.getFrame(msg.number | 0);
      send({ type: 'frame', seq: msg.seq, frame: plainFrame(res) });
    } catch (err) {
      send({ type: 'frame', seq: msg.seq, error: String(err && err.message || err) });
    }
  },

  'check-filter': function (msg) {
    if (!lib) return send({ type: 'filter-check', seq: msg.seq, ok: false, error: 'engine not ready' });
    try {
      const res = lib.checkFilter(msg.filter || '');
      send({ type: 'filter-check', seq: msg.seq, ok: !!res.ok, error: res.error });
    } catch (err) {
      send({ type: 'filter-check', seq: msg.seq, ok: false, error: String(err && err.message || err) });
    }
  },

  'complete-filter': function (msg) {
    if (!lib) return send({ type: 'filter-complete', seq: msg.seq, fields: [] });
    try {
      const res = lib.completeFilter(msg.field || '');
      send({ type: 'filter-complete', seq: msg.seq, fields: vec2array(res.fields) });
    } catch (err) {
      send({ type: 'filter-complete', seq: msg.seq, fields: [] });
    }
  },

  'follow': function (msg) {
    if (!session) return send({ type: 'follow', seq: msg.seq, error: 'no capture loaded' });
    try {
      const res = session.follow(msg.follower, msg.filter || '');
      send({ type: 'follow', seq: msg.seq, follow: plainFollow(res) });
    } catch (err) {
      send({ type: 'follow', seq: msg.seq, error: String(err && err.message || err) });
    }
  },

  'tap': function (msg) {
    if (!session) return send({ type: 'tap', seq: msg.seq, error: 'no capture loaded', taps: [] });
    try {
      const args = new lib.MapInput();
      for (const k of Object.keys(msg.taps || {})) args.set(k, msg.taps[k]);
      let res;
      try {
        res = session.tap(args);
      } finally {
        if (typeof args.delete === 'function') args.delete();
      }
      send({ type: 'tap', seq: msg.seq, error: res.error, taps: vec2array(res.taps).map(plainTap) });
    } catch (err) {
      send({ type: 'tap', seq: msg.seq, error: String(err && err.message || err), taps: [] });
    }
  },

  'iograph': function (msg) {
    if (!session) return send({ type: 'iograph', seq: msg.seq, error: 'no capture loaded', iograph: [] });
    try {
      const args = new lib.MapInput();
      for (const k of Object.keys(msg.input || {})) args.set(k, msg.input[k]);
      let res;
      try {
        res = session.iograph(args);
      } finally {
        if (typeof args.delete === 'function') args.delete();
      }
      send({
        type: 'iograph', seq: msg.seq, error: res.error,
        iograph: vec2array(res.iograph).map(function (g) {
          const items = vec2array(g.items);
          if (typeof g.delete === 'function') g.delete();
          return { items: items };
        })
      });
    } catch (err) {
      send({ type: 'iograph', seq: msg.seq, error: String(err && err.message || err), iograph: [] });
    }
  },

  'download': function (msg) {
    if (!session) return send({ type: 'download', seq: msg.seq, error: 'no capture loaded' });
    try {
      const res = session.download(msg.token);
      send({ type: 'download', seq: msg.seq, error: res.error, download: res.download || null });
    } catch (err) {
      send({ type: 'download', seq: msg.seq, error: String(err && err.message || err) });
    }
  }
};

/* ----------------------------------------------------------------- rpc */

function send(msg) {
  self.postMessage(msg);
}

self.onmessage = function (event) {
  const msg = event.data || {};
  const handler = handlers[msg.type];
  if (!handler) return;
  try {
    const result = handler(msg);
    if (result && typeof result.catch === 'function') {
      result.catch(function (err) {
        send({ type: 'engine-log', level: 'error', text: 'rpc ' + msg.type + ': ' + (err && err.message || err) });
      });
    }
  } catch (err) {
    send({ type: 'engine-log', level: 'error', text: 'rpc ' + msg.type + ': ' + (err && err.message || err) });
  }
};
